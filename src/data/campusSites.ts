export function getEnabledSites(): CampusSite[] {
  return campusSites.filter((s) => s.enabled)
}

export function getSiteById(id: string): CampusSite | undefined {
  return campusSites.find((s) => s.id === id)
}

export function getEntranceSite(building: 'melville' | 'wang'): CampusSite | undefined {
  return campusSites.find(
    (s) => s.enabled && s.isBuildingEntrance && s.entranceFor === building,
  )
}
